import pandas as pd
import matplotlib.pyplot as plt

# Cricket Dataset - 15 Players
data = {
    "Player": [
        "Rohit", "Virat", "Gill", "Rahul", "Surya",
        "Dhoni", "Hardik", "Jadeja", "Bumrah", "Pant",
        "Sam", "Jos", "Buttler", "Stokes", "Brook"
    ],
    "Team": [
        "India", "India", "India", "India", "India",
        "India", "India", "India", "India", "India",
        "England", "England", "England", "England", "England"
    ],
    "Runs": [
        95, 120, 75, None, 88,
        45, 65, 55, 20, 82,
        70, 105, None, 60, 90
    ]
}

df = pd.DataFrame(data)

# Function to perform all 12 exercises
def cricket_analysis(choice):

    match choice:

        case 1:
            print("\nComplete Cricket Dataset:")
            print(df)

        case 2:
            print("\nFirst Five Records:")
            print(df.head())
            print("\nLast Five Records:")
            print(df.tail())

        case 3:
            print("\nMissing Values in Each Column:")
            print(df.isnull().sum())

        case 4:
            df["Runs"] = df["Runs"].fillna(df["Runs"].mean())
            print("\nMissing Runs Filled Using Mean:")
            print(df)

        case 5:
            print("\nAverage Runs:", df["Runs"].mean())
            print("Highest Runs:", df["Runs"].max())
            print("Lowest Runs:", df["Runs"].min())

        case 6:
            print("\nPlayers Scoring More Than 80 Runs:")
            print(df[df["Runs"] > 80])

        case 7:
            print("\nRuns in Ascending Order:")
            print(df.sort_values(by="Runs", ascending=True))

        case 8:
            print("\nRuns in Descending Order:")
            print(df.sort_values(by="Runs", ascending=False))

        case 9:
            print("\nPlayer with Highest Runs:")
            print(df.loc[df["Runs"].idxmax()])

        case 10:
            print("\nPlayer with Lowest Runs:")
            print(df.loc[df["Runs"].idxmin()])

        case 11:
            print("\nAverage Runs by Each Team:")
            print(df.groupby("Team")["Runs"].mean())

        case 12:
            print("\nBar Chart of Players' Runs:")
            plt.figure(figsize=(10, 5))
            plt.bar(df["Player"], df["Runs"])
            plt.xlabel("Player")
            plt.ylabel("Runs")
            plt.title("Cricket Player Performance Analysis")
            plt.xticks(rotation=45)
            plt.tight_layout()
            plt.show()

        case 0:
            print("Thank you!")

        case _:
            print("Invalid choice! Enter a number from 0 to 12.")


# Menu-Driven Program
while True:
    print("\n===== CRICKET PLAYER PERFORMANCE ANALYSIS =====")
    print("1. Display complete dataset")
    print("2. Display first and last five records")
    print("3. Count missing values")
    print("4. Fill missing runs using mean")
    print("5. Average, highest and lowest runs")
    print("6. Players scoring more than 80 runs")
    print("7. Sort runs in ascending order")
    print("8. Sort runs in descending order")
    print("9. Display highest scorer using idxmax()")
    print("10. Display lowest scorer using idxmin()")
    print("11. Average runs by team using groupby()")
    print("12. Draw bar chart")
    print("0. Exit")

    try:
        choice = int(input("Enter your choice: "))
        if choice == 0:
            cricket_analysis(choice)
            break
        cricket_analysis(choice)

    except ValueError:
        print("Please enter a valid integer.")